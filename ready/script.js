const menu = document.querySelector('.menu');
const overlay = document.querySelector('.overlay');
const languageSwitches = document.querySelectorAll('.footer-languages');
const languageButtons = document.querySelectorAll('[data-language]');
let currentLanguage = 'ru';

function textFor(key) {
  const value = translations[currentLanguage][key] || translations.ru[key] || key;
  if (currentLanguage !== 'ru') return value;
  return value.replace(/(^|[\s>])(или|и)\s+/gi, '$1$2\u00a0');
}

function updateMenuLabel() {
  const open = overlay.classList.contains('open');
  menu.setAttribute('aria-label', open ? textFor('menuClose') : textFor('menuOpen'));
}

function setLanguage(language, updateUrl = false) {
  currentLanguage = language === 'en' ? 'en' : 'ru';
  document.documentElement.lang = currentLanguage;
  document.querySelector('meta[name="description"]').setAttribute('content', textFor('metaDescription'));
  document.querySelector('.wordmark').setAttribute('aria-label', textFor('wordmarkLabel'));
  document.querySelector('.showcase-track')?.setAttribute('aria-label', textFor('showcaseAria'));
  languageSwitches.forEach(languageSwitch => {
    languageSwitch.setAttribute('aria-label', textFor('languageLabel'));
    languageSwitch.dataset.current = currentLanguage;
  });

  document.querySelectorAll('[data-i18n]').forEach(element => {
    element.textContent = textFor(element.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach(element => {
    element.innerHTML = textFor(element.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(element => {
    element.setAttribute('alt', textFor(element.dataset.i18nAlt));
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
    element.setAttribute('aria-label', textFor(element.dataset.i18nAriaLabel));
  });
  const currentExampleTitle = document.querySelector('.examples-current-title');
  if (currentExampleTitle) currentExampleTitle.textContent = textFor(`examples.${currentExample}Title`);
  languageButtons.forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.language === currentLanguage));
  });
  updateMenuLabel();

  try {
    localStorage.setItem('model-ready-language', currentLanguage);
  } catch (error) {
    // The language still works when storage is unavailable.
  }

  if (updateUrl) {
    const url = new URL(window.location.href);
    url.searchParams.set('lang', currentLanguage);
    history.replaceState(null, '', url);
  }
}

function initialLanguage() {
  const requested = new URLSearchParams(window.location.search).get('lang');
  if (requested === 'ru' || requested === 'en') return requested;
  try {
    const saved = localStorage.getItem('model-ready-language');
    if (saved === 'ru' || saved === 'en') return saved;
  } catch (error) {
    // Fall back to the browser language.
  }
  return navigator.language.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

function toggleMenu(force) {
  const open = typeof force === 'boolean' ? force : !overlay.classList.contains('open');
  overlay.classList.toggle('open', open);
  menu.classList.toggle('active', open);
  menu.setAttribute('aria-expanded', String(open));
  overlay.setAttribute('aria-hidden', String(!open));
  document.body.style.overflow = open ? 'hidden' : '';
  updateMenuLabel();
}

languageButtons.forEach(button => {
  button.addEventListener('click', () => setLanguage(button.dataset.language, true));
});
menu.addEventListener('click', () => toggleMenu());
overlay.querySelectorAll('a').forEach(link => link.addEventListener('click', () => toggleMenu(false)));

const examplesModal = document.querySelector('.examples-modal');
const examplePanels = document.querySelectorAll('[data-example-panel]');
const snapReel = document.querySelector('.snap-reel');
let exampleTrigger = null;
let currentExample = 'snaps';

function syncSnapReel(name) {
  if (!snapReel) return;
  if (name === 'snaps' && examplesModal.open && !window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
    snapReel.currentTime = 0;
    snapReel.play().catch(() => undefined);
  } else {
    snapReel.pause();
  }
}

function selectExample(name) {
  currentExample = name;
  examplePanels.forEach(panel => { panel.hidden = panel.dataset.examplePanel !== name; });
  document.querySelector('.examples-current-title').textContent = textFor(`examples.${name}Title`);
  const content = examplesModal.querySelector('.examples-content');
  content.scrollTop = 0;
  syncSnapReel(name);
}

function openExample(name, trigger) {
  exampleTrigger = trigger;
  selectExample(name);
  examplesModal.showModal();
  document.body.classList.add('modal-open');
  syncSnapReel(name);
}

document.querySelectorAll('[data-example]').forEach(button => {
  button.addEventListener('click', () => openExample(button.dataset.example, button));
});
examplesModal.querySelector('.examples-close').addEventListener('click', () => examplesModal.close());
examplesModal.addEventListener('click', event => {
  if (event.target === examplesModal) examplesModal.close();
});
examplesModal.addEventListener('close', () => {
  snapReel?.pause();
  document.body.classList.remove('modal-open');
  exampleTrigger?.focus();
});

setLanguage(initialLanguage());

const observer = new IntersectionObserver(entries => {
  entries.forEach(entry => {
    if (entry.isIntersecting) entry.target.classList.add('visible');
  });
}, { threshold: .18 });

document.querySelectorAll('.page, .philosophy').forEach(page => observer.observe(page));
